// Paleta do herói com a pele da espécie
Sprites.heroPal = function (cls, species) {
  const base = HERO_PALS[cls] || HERO_PALS.fighter;
  const sp = SPECIES[species];
  if (!sp || !base.s) return base;
  return Object.assign({}, base, { s: sp.skin });
};

// Retrato da espécie: NPC + acessórios (compostos no nível do texto)
Sprites.speciesSprite = function (id) {
  const key = 'npc_' + id;
  if (!SPR[key]) {
    const sp = SPECIES[id];
    const rows = SPR.npc.map(r => r.split(''));
    for (const a of (sp.acc || [])) {
      const A = ACCESSORIES[a];
      for (const y in A.rows) {
        const line = A.rows[y];
        for (let x = 0; x < line.length; x++) {
          if (line[x] === '.') continue;
          if (A.mode === 'over' || rows[y][x] === '.') rows[y][x] = line[x];
        }
      }
    }
    SPR[key] = rows.map(r => r.join(''));
  }
  return key;
};
Sprites.speciesPal = function (id) {
  const sp = SPECIES[id];
  return {
    s: sp.skin, e: sp.eyes || '#1c1a26', h: sp.hair || '#4a3a2a', c: sp.cloak, a: U.shade(sp.cloak, 0.18), b: U.shade(sp.cloak, -0.45),
    k: '#3a2a20', z: sp.accColor || sp.hair || '#ffffff',
  };
};
Sprites.speciesUrl = function (id, scale = 3) { return this.url(this.speciesSprite(id), this.speciesPal(id), scale); };
Sprites.classUrl = function (cls, species, scale = 3) { return this.url(CLASSES[cls].sprite, this.heroPal(cls, species), scale); };
